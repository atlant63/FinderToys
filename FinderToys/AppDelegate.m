static CGEventRef eventTapCallback(CGEventTapProxy proxy, CGEventType type, CGEventRef event, void *refcon) {
    if (type == kCGEventTapDisabledByTimeout || type == kCGEventTapDisabledByUserInput) {
        if (sEventTap) {
            CGEventTapEnable(sEventTap, true);
        }
        return event;
    }

    if (type != kCGEventKeyDown) {
        return event;
    }

    if (sIsSynthesizing) {
        return event;
    }

    // Ignore synthetic events generated by MacNewFile
    if (CGEventGetIntegerValueField(event, kCGEventSourceUserData) == FT_SYNTHETIC_TAG) {
        return event;
    }

    // Only intercept when Finder is the frontmost application
    NSRunningApplication *frontApp = [[NSWorkspace sharedWorkspace] frontmostApplication];
    if (![frontApp.bundleIdentifier isEqualToString:@"com.apple.finder"]) {
        return event;
    }

    CGEventFlags flags = CGEventGetFlags(event);

    BOOL hasCmd = (flags & kCGEventFlagMaskCommand) != 0;
    BOOL hasShift = (flags & kCGEventFlagMaskShift) != 0;
    BOOL hasAlt = (flags & kCGEventFlagMaskAlternate) != 0;
    BOOL hasCtrl = (flags & kCGEventFlagMaskControl) != 0;

    CGKeyCode keyCode = (CGKeyCode)CGEventGetIntegerValueField(event, kCGKeyboardEventKeycode);
    BOOL isReturnKey = (keyCode == 36 || keyCode == 76);
    BOOL isCmdR = (keyCode == 15 && hasCmd && !hasShift && !hasAlt && !hasCtrl);
    BOOL isF2Trigger = (keyCode == 120 || keyCode == 144) && !hasCmd && !hasCtrl;
    BOOL isCmdV = (keyCode == 9 && hasCmd && !hasShift && !hasAlt && !hasCtrl);
    BOOL isOptOrShiftReturn = isReturnKey && (hasAlt || hasShift) && !hasCmd && !hasCtrl;

    // Fast-path: if not a key we care about, pass through immediately with zero overhead!
    if (!isReturnKey && !isCmdR && !isF2Trigger && !isCmdV) {
        return event;
    }

    // Check if user is currently typing in an editable field (renaming a file, searching, or in Go to folder)
    BOOL isEditingText = NO;
    AXUIElementRef systemWide = AXUIElementCreateSystemWide();
    if (systemWide) {
        AXUIElementRef focused = NULL;
        if (AXUIElementCopyAttributeValue(systemWide, kAXFocusedUIElementAttribute, (CFTypeRef *)&focused) == kAXErrorSuccess && focused) {
            CFStringRef role = NULL;
            if (AXUIElementCopyAttributeValue(focused, kAXRoleAttribute, (CFTypeRef *)&role) == kAXErrorSuccess && role) {
                if (CFEqual(role, CFSTR("AXTextField")) || CFEqual(role, CFSTR("AXTextArea")) || CFEqual(role, CFSTR("AXComboBox"))) {
                    isEditingText = YES;
                }
                CFRelease(role);
            }
            CFRelease(focused);
        }
        CFRelease(systemWide);
    }

    BOOL isRenameTrigger = isCmdR || isF2Trigger || isOptOrShiftReturn;
    if (isRenameTrigger) {
        if (isEditingText) {
            return event;
        }

        // Send clean Return directly to Finder PID to trigger native rename without event tap interception
        pid_t finderPid = frontApp.processIdentifier;
        CGEventSourceRef source = CGEventSourceCreate(kCGEventSourceStateHIDSystemState);
        CGEventRef down = CGEventCreateKeyboardEvent(source, 36, true); // Return
        CGEventSetFlags(down, 0); // Clean return without modifiers
        CGEventPostToPid(finderPid, down);
        CFRelease(down);

        CGEventRef up = CGEventCreateKeyboardEvent(source, 36, false);
        CGEventSetFlags(up, 0);
        CGEventPostToPid(finderPid, up);
        CFRelease(up);
        CFRelease(source);

        return NULL; // Suppress original trigger
    }

    // 2. Open trigger: Clean Return / Keypad Enter (keyCode 36 or 76) without Cmd, Alt, Ctrl, Shift
    BOOL hasAnyModifier = hasCmd || hasShift || hasAlt || hasCtrl;
    if (isReturnKey && !hasAnyModifier) {
        if (![[NSUserDefaults standardUserDefaults] boolForKey:kEnterToOpenDefaultsKey]) {
            return event;
        }

        if (isEditingText) {
            // In a text field (renaming, search, etc.) - let Return work normally to commit rename!
            return event;
        }

        // Open selected item using Cmd + Down Arrow (keyCode 125) directly to Finder PID
        pid_t finderPid = frontApp.processIdentifier;
        CGEventSourceRef source = CGEventSourceCreate(kCGEventSourceStateHIDSystemState);
        CGEventRef down = CGEventCreateKeyboardEvent(source, 125, true);
        CGEventSetFlags(down, kCGEventFlagMaskCommand);
        CGEventPostToPid(finderPid, down);
        CFRelease(down);

        CGEventRef up = CGEventCreateKeyboardEvent(source, 125, false);
        CGEventSetFlags(up, kCGEventFlagMaskCommand);
        CGEventPostToPid(finderPid, up);
        CFRelease(up);
        CFRelease(source);

        return NULL; // Suppress original Return
    }

    // 3. Paste Clipboard -> File: ⌘V (keyCode 9)
    if (keyCode == 9 && hasCmd && !hasShift && !hasAlt && !hasCtrl) {
        if (isEditingText) {
            // When editing text in Finder (e.g. renaming file, search box, Go to folder), let Cmd+V paste text into the field!
            return event;
        }

        if ([[NSUserDefaults standardUserDefaults] boolForKey:kPasteClipboardDefaultsKey]) {
            if ([AppDelegate handlePasteInFinder]) {
                return NULL; // Handled: file created from clipboard! Suppress native paste.
            }
        }
    }

    return event;
}

