static inline NSString *FTAppLocalizedString(NSString *key) {
    static NSBundle *bundle = nil;
    static dispatch_once_t onceToken;
    dispatch_once(&onceToken, ^{
        NSBundle *mainBundle = [NSBundle mainBundle];
        NSArray *preferred = [NSBundle preferredLocalizationsFromArray:[mainBundle localizations] forPreferences:[NSLocale preferredLanguages]];
        NSString *lang = preferred.firstObject ?: @"en";
        NSString *path = [mainBundle pathForResource:lang ofType:@"lproj"];
        if (path) {
            bundle = [NSBundle bundleWithPath:path];
        }
        if (!bundle) {
            bundle = mainBundle;
        }
    });
    return [bundle localizedStringForKey:key value:key table:nil];
}
#undef NSLocalizedString
#define NSLocalizedString(key, comment) FTAppLocalizedString(key)

